import { test, expect, type Page } from '@playwright/test'

async function createTask(page: Page, title: string) {
  await page.goto('/tasks')
  await page.getByRole('button', { name: 'New task', exact: true }).click()
  await page.getByLabel('Title *', { exact: true }).fill(title)
  await page.getByRole('button', { name: 'Save task', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
test('task create, edit, complete, search, reload, and delete', async ({ page }) => {
  await createTask(page, 'Study Logistic Regression')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Study Logistic Regression' })).toBeVisible()
  await page.getByRole('button', { name: 'Edit Study Logistic Regression', exact: true }).click()
  await page.getByLabel('Title *', { exact: true }).fill('Study and implement regression')
  await page.getByRole('button', { name: 'Save task', exact: true }).click()
  await page.getByRole('button', { name: 'Complete Study and implement regression', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reopen Study and implement regression', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Filter entries' }).selectOption('Completed')
  await page.getByRole('textbox', { name: 'Search tasks' }).fill('unmatched')
  await expect(page.getByText('No matching entries')).toBeVisible()
  await page.getByRole('textbox', { name: 'Search tasks' }).fill('')
  await page.getByRole('button', { name: 'Delete Study and implement regression', exact: true }).click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.reload()
  await expect(page.getByText('Your tasks start here')).toBeVisible()
})
test('export, rejected import, clear confirmation, and restore', async ({ page }) => {
  await createTask(page, 'Backup round trip')
  await page.goto('/settings')
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export Data', exact: true }).click()
  const download = await downloaded
  expect(download.suggestedFilename()).toBe('personal-os-backup.json')
  const backupPath = await download.path()
  await page.getByLabel('Import Data', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"app":"personal-os","version":1,"data":{}}') })
  await expect(page.getByRole('alert')).toContainText('Unsupported backup')
  await page.goto('/tasks')
  await expect(page.getByRole('heading', { name: 'Backup round trip' })).toBeVisible()
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Clear Local Data', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Clear everything' })).toBeDisabled()
  await page.getByLabel('Type CLEAR to confirm').fill('CLEAR')
  await page.getByRole('button', { name: 'Clear everything' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByLabel('Import Data', { exact: true }).setInputFiles(backupPath!)
  await page.getByRole('button', { name: 'Confirm merge' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/tasks')
  await expect(page.getByRole('heading', { name: 'Backup round trip' })).toBeVisible()
})
test('study timer persists across reload and saves a real session', async ({ page }) => {
  await page.goto('/time-tracking')
  await page.getByLabel('Topic *', { exact: true }).fill('Neural networks')
  await page.getByRole('button', { name: 'Start session', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Topic *', { exact: true })).toHaveValue('Neural networks')
  await expect(page.getByRole('timer')).not.toHaveText('00:00:00')
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  await page.getByRole('button', { name: 'Stop & save', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Session saved' })).toBeVisible()
  await page.goto('/study-sessions')
  await expect(page.getByRole('heading', { name: 'Neural networks' })).toBeVisible()
})
