test('mobile navigation, every route, theme, and offline reload', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('link', { name: 'Tasks', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tasks', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open navigation' })).toHaveAttribute('aria-expanded', 'false')
  for (const route of ['/habits', '/time-tracking', '/courses', '/skills', '/study-sessions', '/projects', '/goals', '/finance', '/finance/transactions', '/finance/budget', '/information', '/information/ai-ml', '/information/cse', '/information/software', '/information/career', '/information/study-abroad', '/information/scholarships', '/information/competitions', '/information/hackathons', '/analytics', '/insights', '/settings', '/notes', '/read-later', '/opportunities']) {
    await page.goto(route)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `${route} should fit mobile width`).toBeTruthy()
  }
  await page.getByRole('button', { name: 'Toggle light and dark theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.goto('/')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: 'test-results/dashboard-dark.png', fullPage: true })
  await page.evaluate(() => navigator.serviceWorker.ready)
  await context.setOffline(true)
  await page.goto('/tasks')
  await expect(page.getByRole('heading', { name: 'Tasks', exact: true })).toBeVisible()
  await createTask(page, 'Created while offline')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Created while offline' })).toBeVisible()
  expect(errors).toEqual([])
})
test('external feeds are opt-in, tolerate provider failure, and save normalized articles', async ({ page }) => {
  let externalRequests = 0
  await page.route('https://dev.to/api/**', async route => { externalRequests++; await route.fulfill({ json: [{ id: 1, title: 'ML testing article', url: 'https://dev.to/example/ml', description: 'Fixture for provider adapter testing', tag_list: ['machinelearning'], published_at: '2026-09-13T12:00:00Z' }] }) })
  await page.route('https://hn.algolia.com/**', async route => { externalRequests++; await route.fulfill({ status: 503, body: 'Unavailable' }) })
  await page.goto('/information/ai-ml')
  await expect(page.getByText('Fresh information, on your terms')).toBeVisible()
  expect(externalRequests).toBe(0)
  await page.getByRole('button', { name: 'Fetch public updates' }).click()
  await expect(page.getByRole('heading', { name: 'ML testing article' })).toBeVisible()
  await expect(page.getByText('Hacker News / Algolia is unavailable. Try again later.')).toBeVisible()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Saved', exact: true })).toBeDisabled()
  await page.goto('/read-later')
  await expect(page.getByRole('heading', { name: 'ML testing article' })).toBeVisible()
})
